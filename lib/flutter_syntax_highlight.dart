/// Dart 소스를 구문 강조해 그리는, 두 층으로 나뉜 패키지.
///
/// **아래층은 순수 Dart 토크나이저다.** 아무것도 import하지 않는다 — Flutter도,
/// `dart:*`도. 그래서 위젯도 pump도 없이 테스트되고, 그것이 이 패키지의 이음매다:
/// 토크나이저는 kind가 *무엇인지*를 정하고, 위젯은 kind가 *어떻게 보이는지*를
/// 정한다. 토크나이저가 `Color`를 아는 순간 두 층은 용접되고, 그러면 렌더링 없이는
/// 아무것도 검증할 수 없게 된다.
///
/// **토크나이저가 돌려주는 것은 partition이다**: 모든 토큰의 텍스트를 순서대로
/// 이어 붙이면 입력과 바이트 단위로 같다. 토큰은 기록된 오프셋에서 잘라 내며 다시
/// 만들어지지 않으므로, 문자가 떨어지거나 겹치거나 고쳐 쓰이는 경로 자체가 없다.
///
/// **위층은 얇은 위젯이다.** 소스 문자열을 받아 선택 가능하고 복사 가능한 텍스트로
/// 그린다. 팔레트는 kind에서 스타일로 가는 평범한 Map이고, 기본값은 소비자의
/// `ColorScheme`에서 파생되므로 설정 없이 라이트와 다크 양쪽에서 맞는다.
///
/// **Dart 전용이고, 의도적으로 거칠다.** 타입과 변수를 구분하지 않는다 — 그것은
/// 파서가 필요하고, 이름이 *무엇을 뜻하는지*에 대한 반쯤 맞는 답은 답이 없는 것보다
/// 나쁘다. 읽는 사람이 그것을 믿어 버리기 때문이다.
///
/// 아직 아무것도 내보내지 않는다. 이 파일은 공개 진입점의 자리를 잡을 뿐이고,
/// 토크나이저가 들어오면서 채워진다.
